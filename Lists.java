import java.util.Arrays;


public class Lists {
    public static int[] getarr(int[] arr){
        for(int i=0;i<arr.length;i++){
            System.out.println(arr[i]);
        }
    }
    public static void main(String[] args) {
       int ar={10,20,30,40,50};
       getarr(ar);
    }
}
